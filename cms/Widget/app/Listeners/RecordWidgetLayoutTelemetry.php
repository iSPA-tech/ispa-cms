<?php

declare(strict_types=1);

namespace Cms\Widget\Listeners;

use Cms\Widget\Events\WidgetLayoutPublished;
use Cms\Widget\Events\WidgetLayoutRolledBack;
use Cms\Widget\Observability\WidgetRuntimeTelemetry;
use Throwable;

/**
 * Owns telemetry recording for BOTH {@see WidgetLayoutPublished} and
 * {@see WidgetLayoutRolledBack} (plan Chunk 2 Task 24, DoD 1281). Mapped to
 * both events in {@see \Cms\Widget\Providers\EventServiceProvider}, running
 * alongside (never instead of)
 * {@see \Cms\Widget\Listeners\InvalidateWidgetPlacementCache} -- Laravel
 * dispatches every mapped listener for one event independently, so this
 * class owns ONLY the telemetry side effect and never touches the cache.
 *
 * Uses each event's own `correlationId` (already generated by the
 * publishing/rollback service before dispatch) as the correlation metadata
 * DoD 1282 requires for safe/observable listener failure -- no new
 * correlation mechanism is invented here.
 *
 * Failure is safe and observable (DoD 1282): identical reasoning to
 * {@see InvalidateWidgetPlacementCache}'s own docblock.
 */
final class RecordWidgetLayoutTelemetry
{
    private readonly WidgetRuntimeTelemetry $telemetry;

    public function __construct(?WidgetRuntimeTelemetry $telemetry = null)
    {
        $this->telemetry = $telemetry ?? new WidgetRuntimeTelemetry();
    }

    public function handle(WidgetLayoutPublished|WidgetLayoutRolledBack $event): void
    {
        try {
            if ($event instanceof WidgetLayoutPublished) {
                $this->telemetry->recordPublish($event->projectName, $event->layoutUuid, $event->releaseVersion, $event->correlationId);

                return;
            }

            $this->telemetry->recordRollback(
                $event->projectName,
                $event->layoutUuid,
                $event->releaseVersion,
                $event->sourceReleaseVersion,
                $event->correlationId,
            );
        } catch (Throwable $exception) {
            report($exception);
        }
    }
}
