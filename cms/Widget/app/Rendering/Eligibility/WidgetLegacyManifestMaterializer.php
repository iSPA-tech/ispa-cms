<?php

declare(strict_types=1);

namespace Cms\Widget\Rendering\Eligibility;

use App\Contracts\Widget\CanonicalWidgetSchemaResolver;
use Cms\Core\Models\Widget;
use Cms\Core\Models\WidgetTheme;
use Cms\Core\Services\Widget\LegacyWidgetArtifactSetPublisher;
use Cms\Widget\Models\WidgetArtifactManifest as WidgetArtifactManifestModel;
use Cms\Widget\Rendering\ApprovedLegacyWidgetRenderer;
use Cms\Widget\Rendering\Artifacts\WidgetArtifactBuilder;
use Cms\Widget\Rendering\Artifacts\WidgetArtifactManifest as WidgetArtifactManifestVo;
use Cms\Widget\Rendering\Artifacts\WidgetArtifactManifestRepository;
use Cms\Widget\Rendering\DataProviders\CanonicalJson;
use Cms\Widget\Rendering\DataProviders\WidgetDataProviderRegistry;

/**
 * Materializes (or idempotently reuses) a pending, project-scoped Widget
 * Artifact Manifest for one legacy (Widget, Theme) pairing (plan Chunk 2
 * Task 15a, 
 * lines 886-920).
 *
 * FIXED ORDER (checklist item 2, never reordered): resolve canonical
 * Definition/Theme source, schema, applicability, and provider executable
 * contracts -> build/locate and verify the project Blob -> compute the
 * canonical Manifest/`manifest_hash` -> persist/reuse it in `pending` ->
 * only THEN read back its current attestation state. This class never
 * calls {@see WidgetSiteLayoutEligibility::evaluate()} -- eligibility
 * testing before Blob/Manifest identity exists is exactly what the fixed
 * order forbids, and evaluating eligibility is an unrelated consumer's job
 * ({@see \Cms\Widget\Rendering\ApprovedLegacyWidgetRenderer}).
 *
 * BYTE SOURCE (disclosed deviation, see
 * Cms\Core\Services\Widget\LegacyWidgetArtifactSetPublisher::renderThemeContent()
 * docblock): this is the first real caller sourcing actual generated bytes
 * into {@see WidgetArtifactBuilder::build()}. The publisher's rendering
 * algorithm is reused verbatim via its newly-widened public seam -- never
 * forked or reimplemented -- so Manifest `artifact_hash` always matches
 * what the legacy publisher itself would generate for the identical
 * (Widget, Theme) pair.
 *
 * PROVIDER CONTRACTS: only provider KEY/VERSION/`provider_contract_hash`
 * ever enters Manifest identity, never ordinary business arguments or
 * Input Values (D-034). Legacy `{query:type.name ...}` placeholder syntax
 * IS the provider registry key verbatim (verified against
 * App\Services\WidgetQueryService::getQueryData()'s match arms: e.g.
 * `post.latest`, `product.featured` are simultaneously the placeholder
 * grammar's `type.name` and the Task-11 legacy provider adapters' own
 * `key()`, always version 1). A detected key that is not currently
 * registered is skipped, never fabricated -- forward-compatible with
 * whichever later task wires real legacy provider registration.
 *
 * CREATED-VS-REUSED DETECTION: {@see WidgetArtifactBuilder::build()} (Task
 * 10, frozen) does not itself signal new-vs-existing. This class
 * independently computes the same canonical `manifest_hash` BEFORE calling
 * build() (reusing {@see CanonicalJson}, the same canonical-JSON discipline
 * the builder's own private computation uses) to check existence first.
 * {@see \Cms\Widget\Tests\Feature\Rendering\WidgetLegacyManifestMaterializerTest}
 * pins this independently-computed hash equal to the builder's own returned
 * `manifest_hash` for matching inputs, so any future drift between the two
 * algorithms fails loudly instead of silently misreporting 200 vs 201.
 *
 * "READ ATTESTATION": this schema has no separate attestation table --
 * {@see \Cms\Widget\Models\WidgetArtifactManifest} carries
 * `eligibility_state`/`attestation_version` on the SAME row as canonical
 * provenance (Task 13a). Canonical fields never mutate, so reusing an
 * existing exact-hash Manifest also reuses whatever eligibility state that
 * row already has (e.g. a previously-approved fingerprint that reappears
 * after being edited away and back stays approved, no re-approval needed).
 * This class never mutates that state -- only Task 15b's approval service
 * may.
 */
final class WidgetLegacyManifestMaterializer
{
    /** Identifies the byte-generation algorithm that produced Manifest artifact bytes. */
    public const GENERATOR_VERSION = 'legacy-widget-artifact-set-publisher-v1';

    /** Identifies the runtime rendering pathway the resulting artifact is consumed through. */
    public const RENDERER_KEY = 'legacy-blade-widget';

    public const RENDERER_VERSION = 'v1';

    private const MEDIA_TYPE = 'text/x-blade-template';

    /** Every legacy `{query:type.name ...}` provider placeholder is version 1 (no legacy content ever declares a version). */
    private const LEGACY_PROVIDER_VERSION = 1;

    public function __construct(
        private readonly LegacyWidgetArtifactSetPublisher $publisher,
        private readonly CanonicalWidgetSchemaResolver $schemaResolver,
        private readonly LegacyWidgetExecutableSurfaceAnalyzer $analyzer,
        private readonly WidgetArtifactBuilder $builder,
        private readonly WidgetArtifactManifestRepository $manifestRepository,
        private readonly WidgetDataProviderRegistry $providerRegistry,
    ) {
    }

    /**
     * Materialize (or idempotently reuse) exactly one project-scoped pending
     * Manifest for one (widgetId, themeId) pair.
     *
     * @param string|null $expectedSourceFingerprint Optional optimistic-
     *        concurrency check against the freshly recomputed Task-9c
     *        source fingerprint (never the Task-10 artifact-level
     *        `manifest_hash`, which a caller could not have independently
     *        observed). Only the browser materialize endpoint supplies
     *        this; the after-commit listener and the reconciliation
     *        command always pass null (no client expectation to validate).
     */

    /**
     * Read-only companion for the browser materialize flow (route 32): the
     * CURRENT Task-9c source fingerprint for one pairing, so a client can
     * echo it as expected_source_fingerprint instead of materializing blind.
     * Same resolveSource() gate as materialize() — invalid pairings and
     * non-applicable Themes never leak a fingerprint.
     *
     * @return array{ok: bool, reason?: string, source_fingerprint?: string}
     */
    public function inspectSourceFingerprint(int $widgetId, int $themeId, string $projectName): array
    {
        $resolved = $this->resolveSource($widgetId, $themeId, $projectName);

        if (!$resolved['ok']) {
            return ['ok' => false, 'reason' => (string) $resolved['reason']];
        }

        return ['ok' => true, 'source_fingerprint' => (string) $resolved['fingerprint']->manifestHash];
    }

    public function materialize(
        int $widgetId,
        int $themeId,
        string $projectName,
        ?string $expectedSourceFingerprint = null,
    ): WidgetLegacyManifestMaterializationResult {
        $resolved = $this->resolveSource($widgetId, $themeId, $projectName);

        if (!$resolved['ok']) {
            return $resolved['reason'] === 'not_applicable'
                ? WidgetLegacyManifestMaterializationResult::notApplicable($widgetId, $themeId, $projectName)
                : WidgetLegacyManifestMaterializationResult::invalidPairing($widgetId, $themeId, $projectName);
        }

        /** @var WidgetExecutableSurfaceFingerprint $fingerprint */
        $fingerprint = $resolved['fingerprint'];

        if ($expectedSourceFingerprint !== null && !hash_equals($fingerprint->manifestHash, $expectedSourceFingerprint)) {
            return WidgetLegacyManifestMaterializationResult::sourceFingerprintStale($widgetId, $themeId, $projectName, $fingerprint->manifestHash);
        }

        $existedBefore = $this->manifestRepository->findByProjectAndManifestHash($projectName, $resolved['manifestHash']) !== null;

        $manifest = $this->builder->build(
            projectName: $projectName,
            finalBytes: $resolved['bytes'],
            mediaType: self::MEDIA_TYPE,
            generatorVersion: self::GENERATOR_VERSION,
            rendererKey: self::RENDERER_KEY,
            rendererVersion: self::RENDERER_VERSION,
            executableSurfaceFingerprint: $fingerprint,
            providerContracts: $resolved['providerContracts'],
        );

        // Single read-back of the just-persisted row: derives BOTH the
        // scalar attestation pair and the safe column snapshot the HTTP
        // controller projects, so no consumer re-queries the same row.
        $row = $this->findManifestRow($projectName, $manifest->manifestHash);
        $eligibilityState = $row?->eligibility_state ?? WidgetArtifactManifestVo::STATUS_PENDING;
        $attestationVersion = (int) ($row?->attestation_version ?? 1);
        $snapshot = $row === null ? null : $this->safeRowSnapshot($row);

        return $existedBefore
            ? WidgetLegacyManifestMaterializationResult::reused($widgetId, $themeId, $projectName, $manifest, $eligibilityState, $attestationVersion, $fingerprint->manifestHash, $snapshot)
            : WidgetLegacyManifestMaterializationResult::created($widgetId, $themeId, $projectName, $manifest, $eligibilityState, $attestationVersion, $fingerprint->manifestHash, $snapshot);
    }

    /**
     * Read-only drift/health primitive shared with
     * {@see WidgetLegacyManifestDriftReader}: resolves the CURRENT live
     * source fingerprint for one (widget, theme, project) triple and
     * reports whether a Manifest already exists for it, without ever
     * calling the Blob store or the Manifest repository's write path. Safe
     * output only -- never theme content/CSS/JS or any storage path.
     *
     * @return array{applicable: bool, has_current_manifest: bool, manifest_hash: ?string, eligibility_state: ?string, attestation_version: ?int}
     */
    public function inspect(int $widgetId, int $themeId, string $projectName): array
    {
        $resolved = $this->resolveSource($widgetId, $themeId, $projectName);

        if (!$resolved['ok']) {
            return [
                'applicable' => false,
                'has_current_manifest' => false,
                'manifest_hash' => null,
                'eligibility_state' => null,
                'attestation_version' => null,
            ];
        }

        $manifestHash = $resolved['manifestHash'];
        $row = $this->findManifestRow($projectName, $manifestHash);
        $exists = $row !== null;

        $eligibilityState = $row?->eligibility_state;
        $attestationVersion = $row === null ? null : (int) $row->attestation_version;

        return [
            'applicable' => true,
            'has_current_manifest' => $exists,
            'manifest_hash' => $manifestHash,
            'eligibility_state' => $eligibilityState,
            'attestation_version' => $attestationVersion,
        ];
    }

    /**
     * Shared step 1 of the fixed order: resolve canonical Definition/Theme
     * source, schema, applicability, and provider executable contracts, and
     * compute (without persisting) the canonical `manifest_hash` this
     * source would resolve to right now. Renders artifact bytes (needed for
     * `artifact_hash`) but never writes them anywhere -- pure computation.
     *
     * @return array{ok: bool, reason?: string, bytes?: string, fingerprint?: WidgetExecutableSurfaceFingerprint, providerContracts?: list<array{key: string, version: string, provider_contract_hash: string}>, manifestHash?: string}
     */
    private function resolveSource(int $widgetId, int $themeId, string $projectName): array
    {
        if (!$this->schemaResolver->isValidPairing($widgetId, $themeId)) {
            return ['ok' => false, 'reason' => 'invalid_pairing'];
        }

        $widget = Widget::query()->find($widgetId);
        $theme = WidgetTheme::query()->find($themeId);

        if ($widget === null || $theme === null) {
            return ['ok' => false, 'reason' => 'invalid_pairing'];
        }

        // Usable here when the Theme names this project or Default, as on pages. The
        // manifest stays recorded under `$projectName` only; `$applicability` (the Theme's own fan-out list) is
        // hashed unchanged, so existing manifests and attestations keep their identity.
        if (!$theme->isUsableOnProject($projectName)) {
            return ['ok' => false, 'reason' => 'not_applicable'];
        }
        $applicability = $this->applicableProjectNames($theme->project_name);

        $canonicalSchema = $this->schemaResolver->resolve($widgetId, $themeId);
        $bytes = $this->publisher->renderThemeContent($theme);

        $fingerprint = $this->analyzer->analyze(
            widgetJs: (string) $widget->js,
            themeContent: (string) $theme->content,
            themeCss: (string) $theme->css,
            canonicalSchema: $canonicalSchema,
            policyVersion: ApprovedLegacyWidgetRenderer::CURRENT_POLICY_VERSION,
            trustLane: ApprovedLegacyWidgetRenderer::CURRENT_TRUST_LANE,
            applicability: $applicability,
            artifactBytes: $bytes,
        );

        $providerContracts = $this->resolveProviderContracts($fingerprint);
        $artifactHash = hash('sha256', $bytes);
        $manifestHash = $this->computeManifestHash($artifactHash, $fingerprint, $providerContracts);

        return [
            'ok' => true,
            'bytes' => $bytes,
            'fingerprint' => $fingerprint,
            'providerContracts' => $providerContracts,
            'manifestHash' => $manifestHash,
        ];
    }

    /**
     * Map every detected `{query:type.name ...}` provider placeholder key to
     * its registered executable contract hash. `query_keys` is already
     * sorted+unique (Task 9c's analyzer), so the result is naturally
     * ordered too. A key with no currently-registered provider is skipped,
     * never fabricated -- never lets business arguments or Input Values
     * enter this list (D-034), and stays forward-compatible with whichever
     * later task wires real legacy provider registration.
     *
     * `version` is emitted as a STRING (not the `int` the registry lookup
     * itself takes): {@see WidgetArtifactBuilder::normalizeProviderContracts()}
     * casts every entry's `version` to string before it ever reaches the
     * canonical JSON that becomes `manifest_hash` (and WidgetArtifactManifest's
     * own docblock documents the contract shape as `version: string`), so
     * this method matches that exact shape up front rather than relying on
     * the builder's cast alone -- {@see self::computeManifestHash()} must
     * feed CanonicalJson the identical shape the builder itself hashes.
     *
     * @return list<array{key: string, version: string, provider_contract_hash: string}>
     */
    private function resolveProviderContracts(WidgetExecutableSurfaceFingerprint $fingerprint): array
    {
        $contracts = [];

        foreach ($fingerprint->providerSyntax['query_keys'] ?? [] as $queryKey) {
            $hash = $this->providerRegistry->contractHashFor($queryKey, self::LEGACY_PROVIDER_VERSION);
            if ($hash === null) {
                continue;
            }

            $contracts[] = [
                'key' => $queryKey,
                'version' => (string) self::LEGACY_PROVIDER_VERSION,
                'provider_contract_hash' => $hash,
            ];
        }

        return $contracts;
    }

    /**
     * Mirrors {@see WidgetArtifactBuilder::build()}'s own private
     * `manifest_hash` computation field-for-field (see class docblock for
     * why this duplication exists and how it is pinned by a test).
     *
     * @param list<array{key: string, version: string, provider_contract_hash: string}> $providerContracts
     */
    private function computeManifestHash(string $artifactHash, WidgetExecutableSurfaceFingerprint $fingerprint, array $providerContracts): string
    {
        return CanonicalJson::hash([
            'artifact_hash' => $artifactHash,
            'generator_version' => self::GENERATOR_VERSION,
            'renderer_key' => self::RENDERER_KEY,
            'renderer_version' => self::RENDERER_VERSION,
            'applicability' => $fingerprint->applicability,
            'executable_surface_fingerprint_hash' => $fingerprint->manifestHash,
            'canonical_schema_hash' => $fingerprint->canonicalSchemaHash,
            'provider_contracts' => $providerContracts,
            'trust_policy_version' => $fingerprint->policyVersion,
            'trust_lane' => $fingerprint->trustLane,
        ]);
    }

    /**
     * Single Eloquent read of one project-scoped Manifest row (or null).
     * The one place this class reads `widget_artifact_manifests` back --
     * both {@see self::materialize()} (for the scalar attestation pair plus
     * the safe snapshot carried to the controller) and {@see self::inspect()}
     * (drift/health) go through it, so neither the materializer nor its
     * consumers ever double-read the same row.
     */
    private function findManifestRow(string $projectName, string $manifestHash): ?WidgetArtifactManifestModel
    {
        return WidgetArtifactManifestModel::query()
            ->where('project_name', $projectName)
            ->where('manifest_hash', $manifestHash)
            ->first();
    }

    /**
     * Project the SAFE columns of a Manifest row into a plain array carried
     * on the result so the HTTP controller never re-queries the row.
     * Deliberately RAW column names (not resource field names) -- the
     * resource-field renaming (`trust_policy_version` -> `policy_version`)
     * stays an HTTP concern in the controller. Never includes any storage
     * key, source bytes, or Blob metadata.
     *
     * @return array{manifest_hash: string, project_name: string, eligibility_state: string, attestation_version: int, trust_policy_version: string, trust_lane: string, control_version: int, blocked: bool, approved_by: ?int, approved_at: mixed, revoked_by: ?int, revoked_at: mixed}
     */
    private function safeRowSnapshot(WidgetArtifactManifestModel $row): array
    {
        return [
            'manifest_hash' => (string) $row->manifest_hash,
            'project_name' => (string) $row->project_name,
            'eligibility_state' => (string) $row->eligibility_state,
            'attestation_version' => (int) $row->attestation_version,
            'trust_policy_version' => (string) $row->trust_policy_version,
            'trust_lane' => (string) $row->trust_lane,
            'control_version' => (int) $row->control_version,
            'blocked' => (bool) $row->blocked,
            'approved_by' => $row->approved_by,
            'approved_at' => $row->approved_at,
            'revoked_by' => $row->revoked_by,
            'revoked_at' => $row->revoked_at,
        ];
    }

    /**
     * Project/template applicability fan-out. Reimplements the SAME logic as
     * {@see \Cms\Widget\Rendering\ApprovedLegacyWidgetRenderer::applicableProjectNames()}
     * -- that renderer is in this SAME module (imported here for its policy/
     * trust-lane constants), but its `applicableProjectNames()` is a PRIVATE
     * method on a frozen Task 9c surface, so it cannot be called directly;
     * a local copy is the only option short of widening that frozen class.
     * A non-array, non-empty scalar wraps to one name; a non-array empty
     * value falls back to `['Default']`; an array (including empty) is used
     * as-is.
     *
     * @return list<string>
     */
    private function applicableProjectNames(mixed $projectName): array
    {
        if (!is_array($projectName)) {
            return !empty($projectName) ? [(string) $projectName] : ['Default'];
        }

        return array_values(array_map('strval', $projectName));
    }
}
