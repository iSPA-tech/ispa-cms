<?php

declare(strict_types=1);

namespace Cms\Widget\Rendering\Artifacts;

use RuntimeException;

/**
 * Root contract for immutable, project-scoped, content-addressed Widget
 * artifact Blob storage (plan Chunk 1 Task 10; architecture.md
 * "widget_artifact_blobs"; docs/architecture/adr-widget-artifact-store.md
 * decision 10 "Blob/Manifest identity" and "Artifact publication flow").
 *
 * This slice is persistence-agnostic: cms/Widget ships no production
 * implementation of this interface yet.
 * {@see \Cms\Widget\Tests\Fakes\InMemoryWidgetArtifactBlobRepository} is the
 * ONLY implementation, used exclusively by tests, and doubles as the
 * executable behavior contract Task 13b's real database/filesystem adapter
 * must also satisfy.
 * {@see \Cms\Widget\Tests\Unit\Rendering\WidgetArtifactRepositoryTest}
 * asserts through this interface's methods (never fake internals), but
 * reusing it against the Task 13b adapter is NOT drop-in: the suite
 * instantiates the fakes concretely in setUp() and its dedup/isolation
 * proofs rely on the fakes' test-only countRowsForProject() helper (which
 * is deliberately NOT part of this interface), so Task 13b must first
 * extract an abstract contract-test base exposing repository-factory and
 * row-count hooks, then run the same assertions against its real adapter.
 *
 * Adapter acceptance contract (Task 5a topology evidence,
 * docs/evidence/widget-site-layout-preflight.md "4. Artifact topology —
 * proven vs gaps"): production today is a SINGLE application node with one local
 * POSIX disk trivially shared across every process of that deployment,
 * with atomic same-filesystem `rename()` and consistent read-after-write.
 * A real adapter for this interface MUST NOT assume local disk is shared
 * across MULTIPLE public nodes -- per-node local disk on more than one
 * public node, without synchronous distribution, does not pass
 * architecture.md's "Storage topology gate" and requires a fresh Task
 * 5a-grade evidence pass before it may be built.
 *
 * Identity is the composite `(project_name, artifact_hash)`
 * (`artifact_hash = SHA-256(final generated bytes)`, frozen contract
 * "Artifact identity"). Two projects with byte-identical content keep
 * separate rows and storage keys -- MVP performs no cross-project
 * deduplication.
 */
interface WidgetArtifactBlobRepository
{
    /**
     * Read-only lookup. Returns null on a miss -- NEVER throws for an
     * unknown hash.
     *
     * This is also the graceful legacy-ID-fallback contract: a caller
     * holding only legacy `widget_id`/`widget_theme_id` identity (no
     * `artifact_hash` yet) cannot query this repository by legacy ID at
     * all, because `widget_artifact_blobs` rows never carry legacy
     * ownership/manifest metadata (architecture.md's explicit "no
     * manifest, provider, ownership, label, source HTML, or secret-value
     * metadata" invariant). A clean null miss on the not-yet-computed hash
     * is what lets such a caller fall back to the already-accepted legacy
     * resolution chain (`App\Services\WidgetTemplatePathResolver::candidates()`,
     * which resolves `widget_{id}_theme_{id}.blade.php` by legacy ID)
     * instead of this hash-addressed store, with no risk of a fabricated
     * or partially-visible descriptor. The window closes cleanly the
     * moment the same content is published under its real hash -- there is
     * no permanent negative caching trap.
     */
    public function findByProjectAndHash(string $projectName, string $artifactHash): ?WidgetArtifactBlobDescriptor;

    /**
     * Publish (or idempotently reuse) one immutable Blob under
     * `(projectName, artifactHash)`. Implementations MUST simulate the
     * artifact-store ADR's publication flow:
     *
     * 1. independently verify `hash('sha256', $bytes) === $artifactHash`
     *    (the "checksum" step) BEFORE anything becomes visible via
     *    {@see findByProjectAndHash()} -- a mismatch throws
     *    {@see WidgetArtifactIntegrityException::checksumMismatch()} and
     *    publishes nothing (simulates "temp write, verify, only then
     *    atomic rename"; a failed attempt leaves no orphaned/partially
     *    visible entry -- the in-memory analogue of publication cleanup);
     * 2. an existing `(projectName, artifactHash)` row with IDENTICAL
     *    stored bytes returns the EXISTING descriptor untouched -- no
     *    rewrite, no new `createdAt` (idempotent reuse/dedup);
     * 3. an existing row whose stored bytes DIFFER is a hard integrity
     *    failure -- {@see WidgetArtifactIntegrityException::hashCollisionWithDifferentBytes()},
     *    never an overwrite; the retained original descriptor/bytes stay
     *    exactly as they were.
     *
     * True multi-process atomicity (the real `rename(2)` syscall / database
     * transaction) is Task 13b's real adapter's own proof obligation; an
     * in-memory single-process fake can only prove atomicity of VISIBILITY
     * within one process, not cross-process atomicity.
     */
    public function put(string $projectName, string $artifactHash, string $bytes, string $mediaType): WidgetArtifactBlobDescriptor;
}

/**
 * Hard integrity failure for the Blob publication contract. Co-located with
 * WidgetArtifactBlobRepository because Task 10's allowed_paths has no
 * separate slot for an exception file -- always reached only after the
 * interface (or an implementing class's `implements` clause) has already
 * triggered autoloading of this file, mirroring the value-object
 * co-location precedent already established in Task 9c's
 * LegacyWidgetExecutableSurfaceAnalyzer.php.
 */
final class WidgetArtifactIntegrityException extends RuntimeException
{
    public static function checksumMismatch(string $projectName, string $claimedHash): self
    {
        return new self(sprintf(
            "Artifact checksum mismatch publishing project '%s': computed sha256(bytes) does not match claimed artifact_hash '%s'; refusing to publish.",
            $projectName,
            $claimedHash
        ));
    }

    public static function hashCollisionWithDifferentBytes(string $projectName, string $artifactHash): self
    {
        return new self(sprintf(
            "Artifact hash collision for project '%s', artifact_hash '%s': stored bytes differ from the bytes given; an existing hash is never overwritten.",
            $projectName,
            $artifactHash
        ));
    }
}
