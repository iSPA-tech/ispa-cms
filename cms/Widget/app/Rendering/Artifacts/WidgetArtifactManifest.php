<?php

declare(strict_types=1);

namespace Cms\Widget\Rendering\Artifacts;

use DateTimeImmutable;

/**
 * Immutable render/provenance identity for one project-scoped Widget
 * artifact Manifest (plan Chunk 1 Task 10; architecture.md
 * "widget_artifact_manifests" and "Blob and manifest identity";
 * docs/architecture/adr-widget-artifact-store.md decision 10).
 *
 * Canonical manifest fields mirror architecture.md's "Blob and manifest
 * identity" paragraph exactly: artifact hash (via `$artifactBlob`),
 * generator version, renderer key/version, project/template applicability,
 * the normalized source/CSS/executable-surface fingerprint composed from
 * Task 9c's LegacyWidgetExecutableSurfaceAnalyzer, canonical schema hash,
 * provider key/version plus `provider_contract_hash`, and eligibility
 * policy/trust lane. Ordinary provider business arguments and Input Values
 * are structurally absent -- there is no parameter or property through
 * which they could enter (D-034), mirroring
 * WidgetExecutableSurfaceFingerprint's own structural freeze.
 *
 * Many same-project Manifests may reference one Blob (one-Blob-many-
 * Manifests); identity is `(projectName, manifestHash)` even though a real
 * database row would additionally carry a surrogate id. This VO is always
 * `STATUS_PENDING` in this slice -- Task 10 explicitly returns an immutable
 * PENDING descriptor and never approves or persists an approval decision
 * (plan Task 10; non-goal "NO approval/attestation persistence (15a/15b)").
 * Task 15a materializes/persists real pending candidates and Task 15b owns
 * the approve/revoke transition once Task 13a creates storage.
 *
 * NOTE on reconciliation: this Manifest's `manifestHash` is a DIFFERENT,
 * currently-unreconciled identity from
 * Cms\Widget\Rendering\Eligibility\WidgetExecutableSurfaceFingerprint's own
 * `manifestHash` (the Task 9c eligibility-attestation fingerprint). This
 * Manifest folds that entire Task 9c composite hash in wholesale as its
 * `executableSurfaceFingerprintHash` ingredient (proving this Manifest is
 * transitively sensitive to every dimension Task 9c fingerprints: source,
 * CSS, JavaScript, detected executable surfaces, request/session/auth/
 * service access, provider placeholder syntax, canonical schema, policy
 * version, trust lane, applicability) and adds artifact-store-specific
 * ingredients Task 9c does not own (the real `artifact_hash` computed from
 * generated bytes, generator/renderer identity, `provider_contracts`
 * derived from a real Provider Registry rather than mere placeholder-syntax
 * detection). Full reconciliation between the two concepts (e.g. wiring
 * WidgetEligibilityAttestation to reference this row by FK) is explicitly
 * deferred to Task 15a/15b per architecture.md's Instance-Version
 * `artifact_manifest_id` design -- this task does not merge the two
 * concepts.
 */
final readonly class WidgetArtifactManifest
{
    public const STATUS_PENDING = 'pending';

    /**
     * @param list<string> $applicability project/template applicability names, sorted+unique
     * @param list<array{key: string, version: string, provider_contract_hash: string}> $providerContracts
     *        Structured provider executable-contract identity only -- never
     *        ordinary per-Instance business arguments or Input Values.
     */
    public function __construct(
        public string $projectName,
        public string $manifestHash,
        public WidgetArtifactBlobDescriptor $artifactBlob,
        public string $generatorVersion,
        public string $rendererKey,
        public string $rendererVersion,
        public array $applicability,
        public string $executableSurfaceFingerprintHash,
        public string $canonicalSchemaHash,
        public array $providerContracts,
        public string $trustPolicyVersion,
        public string $trustLane,
        public DateTimeImmutable $createdAt,
        public string $status = self::STATUS_PENDING,
    ) {
    }
}
