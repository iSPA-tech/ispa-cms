<?php

declare(strict_types=1);

namespace Cms\Widget\Rendering\Artifacts;

use Cms\Widget\Rendering\Eligibility\WidgetExecutableSurfaceFingerprint;
use DateTimeImmutable;
use InvalidArgumentException;

/**
 * Pure orchestration turning already-generated final bytes plus manifest
 * inputs into an immutable, PENDING WidgetArtifactManifest (plan Chunk 1
 * Task 10; architecture.md "Blob and manifest identity" publication flow
 * steps 1-3 and 7-8 -- steps 4-6, checksum verify / atomic rename /
 * collision check, are owned by the injected WidgetArtifactBlobRepository,
 * not duplicated here).
 *
 * No side effects beyond the two injected repositories: this class performs
 * no filesystem or database I/O of its own and does not generate artifact
 * bytes itself (a caller supplies already-generated bytes). Gate 0's real
 * legacy byte generator is
 * Cms\Core\Services\Widget\LegacyWidgetArtifactSetPublisher, owned by Core
 * and outside cms/Widget's module boundary; it is not wired to this builder
 * in this task (non-goal: "NO wiring into renderers").
 *
 * Composes Task 9c's already-comprehensive
 * WidgetExecutableSurfaceFingerprint (source/CSS/JavaScript, detected
 * executable surfaces, request/session/auth/service access, provider
 * placeholder syntax, canonical schema, policy version, trust lane,
 * applicability) as one input, reusing its fields directly rather than
 * re-deriving them, so this Manifest is transitively sensitive to
 * everything Task 9c already proves sensitive -- see
 * WidgetArtifactManifest's docblock for the explicit "currently
 * unreconciled" note between the two manifest_hash concepts.
 */
final class WidgetArtifactBuilder
{
    public function __construct(
        private readonly WidgetArtifactBlobRepository $blobRepository,
        private readonly WidgetArtifactManifestRepository $manifestRepository,
    ) {
    }

    /**
     * @param list<array{key: string, version: string, provider_contract_hash: string}> $providerContracts
     *        Structured provider executable-contract references only.
     *        Ordinary per-Instance business arguments and Input Values MUST
     *        NOT be passed here (D-034) -- only key/version/
     *        provider_contract_hash participate in Manifest identity.
     */
    public function build(
        string $projectName,
        string $finalBytes,
        string $mediaType,
        string $generatorVersion,
        string $rendererKey,
        string $rendererVersion,
        WidgetExecutableSurfaceFingerprint $executableSurfaceFingerprint,
        array $providerContracts,
    ): WidgetArtifactManifest {
        if ($projectName === '') {
            throw new InvalidArgumentException('WidgetArtifactBuilder::build() requires a non-empty projectName.');
        }

        // Step 1-2 of the publication flow: bytes already built by the
        // caller; artifact_hash is computed purely from those bytes, never
        // supplied independently, so it can never desync from what is
        // actually stored.
        $artifactHash = hash('sha256', $finalBytes);

        // Step 7: persist/reuse the project-scoped Blob (repository owns
        // checksum verification and collision detection).
        $blob = $this->blobRepository->put($projectName, $artifactHash, $finalBytes, $mediaType);

        $normalizedProviderContracts = $this->normalizeProviderContracts($providerContracts);
        $applicability = $this->sortedUnique($executableSurfaceFingerprint->applicability);

        // Step 3: compute the canonical render/provenance Manifest and its
        // manifest_hash. Every named component from architecture.md's
        // "Blob and manifest identity" paragraph is represented as its own
        // canonical JSON key.
        $manifestHash = hash('sha256', $this->canonicalJson([
            'artifact_hash' => $artifactHash,
            'generator_version' => $generatorVersion,
            'renderer_key' => $rendererKey,
            'renderer_version' => $rendererVersion,
            'applicability' => $applicability,
            'executable_surface_fingerprint_hash' => $executableSurfaceFingerprint->manifestHash,
            'canonical_schema_hash' => $executableSurfaceFingerprint->canonicalSchemaHash,
            'provider_contracts' => $normalizedProviderContracts,
            'trust_policy_version' => $executableSurfaceFingerprint->policyVersion,
            'trust_lane' => $executableSurfaceFingerprint->trustLane,
        ]));

        // Step 8: persist/reuse the distinct project-scoped Manifest in
        // pending -- never overwrite or conflict when another Manifest in
        // the same project already references those bytes.
        $existing = $this->manifestRepository->findByProjectAndManifestHash($projectName, $manifestHash);
        if ($existing !== null) {
            return $existing;
        }

        $manifest = new WidgetArtifactManifest(
            projectName: $projectName,
            manifestHash: $manifestHash,
            artifactBlob: $blob,
            generatorVersion: $generatorVersion,
            rendererKey: $rendererKey,
            rendererVersion: $rendererVersion,
            applicability: $applicability,
            executableSurfaceFingerprintHash: $executableSurfaceFingerprint->manifestHash,
            canonicalSchemaHash: $executableSurfaceFingerprint->canonicalSchemaHash,
            providerContracts: $normalizedProviderContracts,
            trustPolicyVersion: $executableSurfaceFingerprint->policyVersion,
            trustLane: $executableSurfaceFingerprint->trustLane,
            createdAt: new DateTimeImmutable(),
        );

        return $this->manifestRepository->putPending($manifest);
    }

    /**
     * Deterministic normalization (validate, dedupe, sort) so canonical
     * JSON ordering never depends on caller input order.
     *
     * @param list<array{key: string, version: string, provider_contract_hash: string}> $providerContracts
     * @return list<array{key: string, version: string, provider_contract_hash: string}>
     */
    private function normalizeProviderContracts(array $providerContracts): array
    {
        $normalized = [];
        $seen = [];

        foreach ($providerContracts as $contract) {
            $key = (string) ($contract['key'] ?? '');
            $version = (string) ($contract['version'] ?? '');
            $contractHash = (string) ($contract['provider_contract_hash'] ?? '');

            if ($key === '' || $version === '' || $contractHash === '') {
                throw new InvalidArgumentException(
                    'Each provider contract requires non-empty key, version, and provider_contract_hash.'
                );
            }

            $dedupeKey = $key . "\0" . $version . "\0" . $contractHash;
            if (isset($seen[$dedupeKey])) {
                continue;
            }
            $seen[$dedupeKey] = true;

            $normalized[] = ['key' => $key, 'version' => $version, 'provider_contract_hash' => $contractHash];
        }

        usort(
            $normalized,
            static fn (array $a, array $b): int => [$a['key'], $a['version'], $a['provider_contract_hash']]
                <=> [$b['key'], $b['version'], $b['provider_contract_hash']]
        );

        return array_values($normalized);
    }

    /**
     * @param array<int, string> $values
     * @return list<string>
     */
    private function sortedUnique(array $values): array
    {
        $unique = array_values(array_unique(array_map('strval', $values)));
        sort($unique);

        return $unique;
    }

    /**
     * Canonical, deterministically-ordered JSON, following the same
     * discipline as
     * \Cms\Core\Services\Widget\LegacyWidgetArtifactGenerationManifest::toCanonicalJson()
     * and
     * \Cms\Widget\Rendering\Eligibility\LegacyWidgetExecutableSurfaceAnalyzer's
     * private canonicalJson() (recursive key sort + JSON_PRETTY_PRINT/
     * JSON_UNESCAPED_SLASHES) so identical logical content always hashes
     * identically regardless of key insertion order.
     *
     * @param array<array-key, mixed> $data
     */
    private function canonicalJson(array $data): string
    {
        return json_encode(
            $this->ksortRecursive($data),
            JSON_THROW_ON_ERROR | JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES
        );
    }

    /**
     * @param array<array-key, mixed> $data
     * @return array<array-key, mixed>
     */
    private function ksortRecursive(array $data): array
    {
        foreach ($data as &$value) {
            if (is_array($value)) {
                $value = $this->ksortRecursive($value);
            }
        }
        unset($value);

        ksort($data);

        return $data;
    }
}
