<?php

declare(strict_types=1);

namespace Cms\Widget\Rendering\Artifacts;

use DateTimeImmutable;

/**
 * Immutable descriptor for one project-scoped, content-addressed Widget
 * artifact Blob (plan Chunk 1 Task 10, 
 * lines 583-612; architecture.md "widget_artifact_blobs" and "Blob and
 * manifest identity"; docs/architecture/adr-widget-artifact-store.md
 * decision 10, D-012/D-042).
 *
 * Mirrors the eventual `widget_artifact_blobs` row shape so Task 13b's real
 * database/storage adapter can bind to this exact field set without a
 * redesign: project-scoped byte metadata ONLY. Per architecture.md's
 * explicit invariant, a Blob descriptor carries NO manifest, provider,
 * ownership, label, source HTML, or secret-value metadata -- that
 * provenance lives exclusively on WidgetArtifactManifest, which references
 * a Blob by `(project_name, artifact_hash)` composite identity, never the
 * reverse.
 *
 * Identity is `(projectName, artifactHash)` where
 * `artifactHash = SHA-256(final generated bytes)` (frozen contract
 * "Artifact identity"). Two projects may independently store byte-identical
 * content under the same hash value -- MVP performs no cross-project
 * deduplication (architecture.md "Storage topology gate").
 *
 * This slice is persistence-agnostic (plan Task 10 non-goals): no
 * filesystem or database write happens anywhere in cms/Widget yet.
 * `storageDisk`/`storageKey` are logical placeholders a real adapter
 * resolves against actual storage after Task 13a creates the table.
 *
 * Adapter acceptance contract (carries Task 5a's proven topology evidence
 * forward, docs/evidence/widget-site-layout-preflight.md "4. Artifact
 * topology — proven vs gaps"): the evidence proves a SINGLE application node with a single
 * local POSIX disk, trivially shared across every process of that one
 * deployment, with same-filesystem atomic `rename()` and consistent
 * read-after-write. A future Task 13b adapter binding `storageDisk`/
 * `storageKey` to per-node LOCAL disk on MULTIPLE public nodes without
 * synchronous distribution does NOT pass architecture.md's "Storage
 * topology gate" and must not be built without a fresh Task 5a-grade
 * runtime evidence pass proving shared storage or synchronous replication
 * for that topology.
 */
final readonly class WidgetArtifactBlobDescriptor
{
    public function __construct(
        public string $projectName,
        public string $artifactHash,
        public int $byteSize,
        public string $mediaType,
        public string $checksum,
        public string $storageDisk,
        public string $storageKey,
        public DateTimeImmutable $createdAt,
    ) {
    }
}
