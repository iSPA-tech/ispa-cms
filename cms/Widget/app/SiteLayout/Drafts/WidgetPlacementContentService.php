<?php

declare(strict_types=1);

namespace Cms\Widget\SiteLayout\Drafts;

use Cms\Widget\Http\Support\WidgetApiErrorResponse;
use Cms\Widget\Instances\WidgetInstanceMutationResult;
use Cms\Widget\Instances\WidgetInstanceService;
use Cms\Widget\Models\WidgetInstance;
use Cms\Widget\Models\WidgetLayoutVersion;
use Cms\Widget\Models\WidgetPlacement;
use Illuminate\Support\Facades\DB;

/**
 * Each Site Layout placement owns its content (Unified Widget Catalog Part 2, Task 3; spec
 * "Area editor": "Internally each placement owns exactly one instance; instances are never
 * listed or shared in the UI. Duplicating a placement duplicates its instance.").
 *
 * Composes the existing services instead of re-implementing them:
 * - a new instance + version 1 goes through {@see WidgetInstanceService::create()} (manifest
 *   auto-approval, blocked-widget 409, module barrier, idempotency);
 * - the placement goes into the draft through {@see WidgetLayoutDraftService::save()}
 *   (slot/scope/target validation, cardinality, positions, registry snapshot, lock_version);
 * - both run in ONE outer transaction, so a stale draft or invalid placement rolls the new
 *   instance (and its idempotency claim) back;
 * - editing the content of a placement that alone owns its instance goes through
 *   {@see UpdateInstanceAndRepinDraft} (new version, repinned); a legacy instance shared by
 *   several placements is forked for the edited placement so the others keep their content.
 *
 * `expected_draft_revision` is the current draft's `lock_version`. Placement uuids are
 * regenerated by every full draft save, so callers always use the uuids of the draft they
 * last received.
 */
final class WidgetPlacementContentService
{
    /** Marks instances owned by a placement, so publish can archive them once unplaced. */
    public const INSTANCE_NAME_PREFIX = 'placement:';

    public function __construct(
        private readonly WidgetInstanceService $instances,
        private readonly WidgetLayoutDraftService $drafts,
        private readonly UpdateInstanceAndRepinDraft $repin,
    ) {
    }

    /**
     * @param array{slot_key: string, scope_type: string, scope_key?: string|null, target_type?: string|null, target_id?: string|null, widget_id: int, widget_theme_id: int, values?: array<string, mixed>} $input
     */
    public function create(string $projectName, string $layoutUuid, ?int $actorId, string $idempotencyKey, int $expectedRevision, array $input): WidgetPlacementContentResult
    {
        $draft = $this->drafts->findCurrentDraft($projectName, $layoutUuid);
        if ($draft === null) {
            return WidgetPlacementContentResult::fromStatus('layout_not_found');
        }

        $row = [
            'slot_key' => (string) $input['slot_key'],
            'scope_type' => (string) $input['scope_type'],
            'scope_key' => $input['scope_key'] ?? null,
            'target_type' => $input['target_type'] ?? null,
            'target_id' => isset($input['target_id']) ? (string) $input['target_id'] : null,
            'enabled' => true,
            'rules' => [],
        ];

        return $this->placeNewInstance(
            $projectName,
            $layoutUuid,
            $draft,
            $actorId,
            'placement-create',
            $idempotencyKey,
            $expectedRevision,
            [
                'name' => self::instanceName($row),
                'widget_id' => (int) $input['widget_id'],
                'widget_theme_id' => (int) $input['widget_theme_id'],
                'values' => is_array($input['values'] ?? null) ? $input['values'] : [],
            ],
            static function (array $document, WidgetInstance $instance) use ($row): array {
                $document[] = $row + [
                    'widget_instance_uuid' => $instance->uuid,
                    'widget_instance_version' => 1,
                    'position' => count($document),
                ];

                return $document;
            },
            201,
        );
    }

    /**
     * `$widgetId` moves the placement to another widget (a site clone of the pinned hub widget,
     * {@see \Cms\Widget\Listeners\RepinPlacementsToClone}); null keeps the pinned widget.
     *
     * @param array<string, mixed> $values
     */
    public function updateContent(string $projectName, string $layoutUuid, string $placementUuid, ?int $actorId, string $idempotencyKey, int $expectedRevision, array $values, ?int $themeId, ?int $widgetId = null): WidgetPlacementContentResult
    {
        $draft = $this->drafts->findCurrentDraft($projectName, $layoutUuid);
        if ($draft === null) {
            return WidgetPlacementContentResult::fromStatus('layout_not_found');
        }

        $placement = $draft->placements->firstWhere('uuid', $placementUuid);
        $pinned = $placement?->instanceVersion;
        $instance = $pinned?->instance;
        if ($placement === null || $instance === null) {
            return WidgetPlacementContentResult::placementNotFound();
        }

        // Checked first so a retried edit answers "draft changed" instead of an idempotency
        // mismatch (the repin request hash includes server-read versions that moved on).
        if ($draft->lock_version !== $expectedRevision) {
            return WidgetPlacementContentResult::fromStatus('stale');
        }

        $input = [
            'widget_id' => $widgetId ?? (int) $pinned->widget_id,
            'widget_theme_id' => $themeId ?? (int) $pinned->widget_theme_id,
            'values' => $values,
            'provider_contract' => is_array($pinned->provider_refs) ? $pinned->provider_refs : [],
        ];

        $sharers = $draft->placements
            ->filter(static fn (WidgetPlacement $p): bool => (int) $p->instanceVersion?->instance_id === (int) $instance->id)
            ->pluck('uuid')
            ->all();

        if (count($sharers) > 1) {
            return $this->placeNewInstance(
                $projectName,
                $layoutUuid,
                $draft,
                $actorId,
                'placement-content',
                $idempotencyKey,
                $expectedRevision,
                ['name' => self::instanceName($placement->toArray())] + $input,
                static function (array $document, WidgetInstance $fork) use ($placementUuid): array {
                    foreach ($document as $index => $row) {
                        if ($row['_uuid'] === $placementUuid) {
                            $document[$index]['widget_instance_uuid'] = $fork->uuid;
                            $document[$index]['widget_instance_version'] = 1;
                        }
                    }

                    return $document;
                },
                200,
            );
        }

        $currentVersion = $instance->currentVersion?->version;
        $result = $this->repin->handle(
            $projectName,
            $layoutUuid,
            $instance->uuid,
            $actorId,
            $idempotencyKey,
            (int) $currentVersion,
            $draft->version,
            $expectedRevision,
            WidgetDraftUsageFingerprint::compute($draft->version, $draft->lock_version, $currentVersion === null ? null : (int) $currentVersion, $sharers),
            $input,
        );

        if ($result->status !== UpdateInstanceAndRepinDraftResult::STATUS_REPINNED) {
            return WidgetPlacementContentResult::fromStatus($result->status);
        }

        // Repin updates the placement row in place, so its uuid is unchanged.
        return WidgetPlacementContentResult::ok($this->drafts->findCurrentDraft($projectName, $layoutUuid) ?? $draft, $placementUuid, 200);
    }

    public function duplicate(string $projectName, string $layoutUuid, string $placementUuid, ?int $actorId, string $idempotencyKey, int $expectedRevision): WidgetPlacementContentResult
    {
        $draft = $this->drafts->findCurrentDraft($projectName, $layoutUuid);
        if ($draft === null) {
            return WidgetPlacementContentResult::fromStatus('layout_not_found');
        }

        $placement = $draft->placements->firstWhere('uuid', $placementUuid);
        $pinned = $placement?->instanceVersion;
        if ($placement === null || $pinned === null) {
            return WidgetPlacementContentResult::placementNotFound();
        }

        return $this->placeNewInstance(
            $projectName,
            $layoutUuid,
            $draft,
            $actorId,
            'placement-duplicate',
            $idempotencyKey,
            $expectedRevision,
            [
                'name' => self::instanceName($placement->toArray()),
                'widget_id' => (int) $pinned->widget_id,
                'widget_theme_id' => (int) $pinned->widget_theme_id,
                'values' => is_array($pinned->values) ? $pinned->values : [],
                'provider_contract' => is_array($pinned->provider_refs) ? $pinned->provider_refs : [],
            ],
            static function (array $document, WidgetInstance $copy) use ($placementUuid): array {
                $result = [];
                foreach ($document as $row) {
                    $result[] = $row;
                    if ($row['_uuid'] === $placementUuid) {
                        // Same submitted position right after the source: the draft save's stable
                        // sort keeps the copy directly below it.
                        $result[] = ['_uuid' => null, 'widget_instance_uuid' => $copy->uuid, 'widget_instance_version' => 1] + $row;
                    }
                }

                return $result;
            },
            201,
        );
    }

    /**
     * Creates the instance and saves the draft document produced by `$place` in one transaction.
     * A replayed request (same Idempotency-Key and body) returns the current draft unchanged.
     *
     * @param array<string, mixed> $instanceInput
     * @param callable(list<array<string, mixed>>, WidgetInstance): list<array<string, mixed>> $place
     */
    private function placeNewInstance(
        string $projectName,
        string $layoutUuid,
        WidgetLayoutVersion $draft,
        ?int $actorId,
        string $keyPrefix,
        string $idempotencyKey,
        int $expectedRevision,
        array $instanceInput,
        callable $place,
        int $successStatus,
    ): WidgetPlacementContentResult {
        $instanceKey = $keyPrefix . ':' . hash('sha256', $layoutUuid . '|' . $idempotencyKey);

        try {
            return DB::transaction(function () use ($projectName, $layoutUuid, $draft, $actorId, $instanceKey, $expectedRevision, $instanceInput, $place, $successStatus): WidgetPlacementContentResult {
                $created = $this->instances->create($projectName, $actorId, $instanceKey, $instanceInput);

                if ($created->status === WidgetInstanceMutationResult::STATUS_REPLAYED) {
                    $current = $this->drafts->findCurrentDraft($projectName, $layoutUuid) ?? $draft;

                    return WidgetPlacementContentResult::ok($current, self::placementUuidOf($current, $created->instance), $successStatus);
                }

                if ($created->status !== WidgetInstanceMutationResult::STATUS_CREATED) {
                    throw new WidgetPlacementContentAborted(WidgetPlacementContentResult::fromStatus($created->status));
                }

                if ($draft->lock_version !== $expectedRevision) {
                    throw new WidgetPlacementContentAborted(WidgetPlacementContentResult::fromStatus('stale'));
                }

                $document = $place(self::documentOf($draft), $created->instance);
                $saved = $this->drafts->save($projectName, $layoutUuid, $draft->version, $expectedRevision, $document);

                if ($saved->status !== WidgetLayoutDraftSaveResult::STATUS_SAVED) {
                    throw new WidgetPlacementContentAborted(WidgetPlacementContentResult::fromStatus($saved->status, $saved->message));
                }

                $current = $this->drafts->findCurrentDraft($projectName, $layoutUuid) ?? $saved->draft;

                return WidgetPlacementContentResult::ok($current, self::placementUuidOf($current, $created->instance), $successStatus);
            });
        } catch (WidgetPlacementContentAborted $aborted) {
            return $aborted->result;
        }
    }

    /**
     * The draft's current placements as a `WidgetLayoutDraftService::save()` document; `_uuid`
     * lets callers find a row and is ignored by the save.
     *
     * @return list<array<string, mixed>>
     */
    private static function documentOf(WidgetLayoutVersion $draft): array
    {
        return $draft->placements
            ->sortBy('position')
            ->values()
            ->map(static fn (WidgetPlacement $p): array => [
                '_uuid' => $p->uuid,
                'slot_key' => $p->slot_key,
                'scope_type' => $p->scope_type,
                'scope_key' => $p->scope_key,
                'target_type' => $p->target_type,
                'target_id' => $p->target_id,
                'widget_instance_uuid' => (string) $p->instanceVersion?->instance?->uuid,
                'widget_instance_version' => (int) $p->instanceVersion?->version,
                'position' => (int) $p->position,
                'enabled' => (bool) $p->enabled,
                'rules' => [],
            ])
            ->all();
    }

    private static function placementUuidOf(WidgetLayoutVersion $draft, ?WidgetInstance $instance): ?string
    {
        if ($instance === null) {
            return null;
        }

        return $draft->placements
            ->sortBy('position')
            ->first(static fn (WidgetPlacement $p): bool => (int) $p->instanceVersion?->instance_id === (int) $instance->id)
            ?->uuid;
    }

    /**
     * Internal name only (instances are never listed in the UI). Including the slot and scope
     * makes a reused Idempotency-Key with a different placement an idempotency mismatch.
     *
     * @param array<string, mixed> $row
     */
    private static function instanceName(array $row): string
    {
        $scope = match ($row['scope_type'] ?? null) {
            WidgetPlacement::SCOPE_TEMPLATE => 'template:' . ($row['scope_key'] ?? ''),
            WidgetPlacement::SCOPE_TARGET => 'target:' . ($row['target_type'] ?? '') . ':' . ($row['target_id'] ?? ''),
            default => 'global',
        };

        return mb_substr(self::INSTANCE_NAME_PREFIX . $row['slot_key'] . ':' . $scope, 0, 255);
    }
}

/**
 * Rolls the outer transaction back while carrying the failure to return. Co-located, like the
 * module's other single-use outcome types.
 */
final class WidgetPlacementContentAborted extends \RuntimeException
{
    public function __construct(public readonly WidgetPlacementContentResult $result)
    {
        parent::__construct('Placement content change aborted: ' . $result->status);
    }
}

/**
 * Outcome of {@see WidgetPlacementContentService}: the current draft on success, otherwise the
 * Widget envelope code (or a plain 404/422 where the module has no code, matching the draft
 * routes).
 */
final readonly class WidgetPlacementContentResult
{
    private function __construct(
        public string $status,
        public int $httpStatus,
        public ?WidgetLayoutVersion $draft = null,
        public ?string $placementUuid = null,
        public ?string $errorCode = null,
        public ?string $message = null,
    ) {
    }

    public static function ok(WidgetLayoutVersion $draft, ?string $placementUuid, int $httpStatus): self
    {
        return new self('ok', $httpStatus, $draft, $placementUuid);
    }

    public static function placementNotFound(): self
    {
        return new self('placement_not_found', 404, message: 'Widget placement not found in the current draft.');
    }

    /**
     * Maps a status of the composed services (instance mutation, draft save, repin) onto the
     * same response each of those routes already gives.
     */
    public static function fromStatus(string $status, ?string $message = null): self
    {
        return match ($status) {
            'layout_not_found' => new self($status, 404, message: 'Widget site layout not found.'),
            'not_found', 'instance_not_found' => new self($status, 404, message: 'Widget instance not found.'),
            'target_not_found' => new self($status, 404, message: 'The requested target was not found.'),
            'validation_failed' => new self($status, 422, message: $message ?? 'The placement is not valid for this area.'),
            'stale', 'draft_stale' => self::coded($status, WidgetApiErrorResponse::WIDGET_DRAFT_STALE, 'The draft changed since it was loaded; refresh and try again.'),
            'usage_changed', 'stale_version' => self::coded($status, WidgetApiErrorResponse::WIDGET_USAGE_CHANGED, 'The placement changed since it was loaded; refresh and try again.'),
            'target_denied' => self::coded($status, WidgetApiErrorResponse::WIDGET_PERMISSION_DENIED, 'You do not have permission to reference the requested target.'),
            'invalid_pairing' => self::coded($status, WidgetApiErrorResponse::WIDGET_MANIFEST_SOURCE_INVALID, 'The requested widget_id/widget_theme_id pairing does not exist.'),
            'not_applicable' => self::coded($status, WidgetApiErrorResponse::WIDGET_MANIFEST_SOURCE_INVALID, 'The requested Theme is not applicable to the authorized project.'),
            'approval_required' => self::coded($status, WidgetApiErrorResponse::WIDGET_MANIFEST_APPROVAL_REQUIRED, 'The Manifest for this widget_id/widget_theme_id pairing is pending approval.'),
            'materialization_failed' => self::coded($status, WidgetApiErrorResponse::WIDGET_MANIFEST_MATERIALIZATION_FAILED, 'Widget manifest materialization failed; this is retryable via reconciliation.'),
            'manifest_blocked' => self::coded($status, WidgetApiErrorResponse::WIDGET_MANIFEST_RUNTIME_BLOCKED, 'The Manifest for this widget_id/widget_theme_id pairing is currently emergency-blocked.'),
            'module_conflict' => self::coded($status, WidgetApiErrorResponse::WIDGET_MODULE_IN_USE, 'The Widget module is currently transitioning; try again shortly.'),
            'idempotency_conflict' => self::coded($status, WidgetApiErrorResponse::WIDGET_IDEMPOTENCY_MISMATCH, 'The same idempotency key was used with a different request payload.'),
            'idempotency_in_progress' => self::coded($status, WidgetApiErrorResponse::WIDGET_IDEMPOTENCY_IN_PROGRESS, 'This request is still being processed; try again shortly.'),
            default => self::coded($status, WidgetApiErrorResponse::WIDGET_ARTIFACT_INTEGRITY_FAILED, 'An unexpected integrity failure occurred.'),
        };
    }

    private static function coded(string $status, string $code, string $message): self
    {
        return new self($status, WidgetApiErrorResponse::statusFor($code), errorCode: $code, message: $message);
    }
}
