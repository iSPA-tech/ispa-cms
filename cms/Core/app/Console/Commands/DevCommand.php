declare(strict_types=1);

namespace Cms\Core\Console\Commands;

use Cms\Core\Services\Toolchain\AdminPaths;
use Cms\Core\Services\Toolchain\ProcessRunner;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

/**
 * `./ispa start`: PHP server, site Vite and admin Vite together, one prefixed output stream, Ctrl+C stops all
 * (spec 5.3). The admin dev server cannot load /iPanel/config.js from PHP, so the site values go into
 * `<admin>/.env.development.local` first (spec 5.2).
 */
class DevCommand extends Command
{
    /** First line of the env file this command writes; a file without it belongs to the owner and is never touched. */
    public const ENV_MARKER = '# Generated by ./ispa start from .env; do not edit.';

    protected $signature = 'cms:dev {--port=8000 : Port of the PHP server} {--admin-port=3000 : Port of the admin dev server}';

    protected $description = 'Start the PHP server, the site Vite server and the admin Vite server together (ispa start).';

    /**
     * Check the toolchain, write the admin dev env, run the three processes.
     */
    public function handle(ProcessRunner $runner, AdminPaths $paths): int
    {
        $adminRoot = $paths->root();
        if ($adminRoot === null) {
            return $this->failWith('The admin sources were not found (looked for admin/package.json and ../base-admin/package.json).', 'Put the admin sources in the admin/ folder.');
        }

        foreach ([$paths->base() => 'the site', $adminRoot => 'the admin'] as $dir => $label) {
            if (! is_dir($dir.'/node_modules')) {
                return $this->failWith("Packages of {$label} are not installed ({$dir}/node_modules is missing).", 'Run `pnpm install` in the site folder, then try again.');
            }
        }

        if ($runner->run(['pnpm', '--version'], null, [], true) !== 0) {
            return $this->failWith('pnpm was not found.', 'Install Node.js 20+ and pnpm (`corepack enable`), then try again.');
        }

        $port = (int) $this->option('port');
        $adminPort = (int) $this->option('admin-port');
        if ($port < 1 || $port > 65535 || $adminPort < 1 || $adminPort > 65535) {
            return $this->failWith('A port is not valid.', 'Use numbers between 1 and 65535.');
        }

        $envFile = $adminRoot.'/.env.development.local';
        if (is_file($envFile) && ! str_starts_with((string) file_get_contents($envFile), self::ENV_MARKER)) {
            return $this->failWith("{$envFile} exists and was not written by ispa; it is left alone.", 'Move it away (or delete it) and run `./ispa start` again.');
        }
        File::put($envFile, $this->envFileBody($port));

        $this->components->info("Site http://127.0.0.1:{$port}  |  admin http://localhost:{$adminPort}/iPanel/  (Ctrl+C stops all)");

        return $runner->parallel([
            'serve' => ['cmd' => [PHP_BINARY, 'artisan', 'serve', '--host=127.0.0.1', '--port='.$port], 'cwd' => $paths->base(), 'env' => []],
            'site' => ['cmd' => ['pnpm', 'exec', 'vite'], 'cwd' => $paths->base(), 'env' => []],
            'admin' => ['cmd' => ['pnpm', '--dir', $adminRoot, 'exec', 'vite', '--port', (string) $adminPort], 'cwd' => $paths->base(), 'env' => []],
        ]);
    }

    /**
     * The admin dev env file: the site values of `.env`, mapped to the `VITE_*` names the admin reads.
     */
    private function envFileBody(int $port): string
    {
        $values = [
            'VITE_BASE_URL' => "127.0.0.1:{$port}",
            'VITE_PROTOCOL' => 'http',
            'VITE_DOMAIN' => '127.0.0.1',
            'VITE_APP_ADMIN_AUTH_KEY' => (string) config('ispa-cms.admin_auth_key', ''),
            'VITE_CMS_API_URL' => (string) config('ispa-cms.platform_hub_url', ''),
        ];

        $lines = [self::ENV_MARKER];
        foreach ($values as $key => $value) {
            $lines[] = $key.'='.$this->quote($value);
        }

        return implode("\n", $lines)."\n";
    }

    /**
     * Double-quote a dotenv value: no line breaks, `\`, `"` and `$` escaped so nothing is expanded.
     */
    private function quote(string $value): string
    {
        $value = str_replace(["\r", "\n"], '', $value);

        return '"'.str_replace(['\\', '"', '$'], ['\\\\', '\\"', '\\$'], $value).'"';
    }

    /**
     * Print the problem and its fix, return the failure code.
     */
    private function failWith(string $problem, string $fix): int
    {
        $this->components->error($problem);
        $this->line('Fix: '.$fix);

        return self::FAILURE;
    }
}
