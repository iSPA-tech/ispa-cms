namespace Cms\Core\Console\Commands;

use Cms\Core\Models\Translate;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Str;
use Throwable;

/**
 * Recovers missing admin translation payload rows from approved historical inventories.
 *
 * Reads an existing admin i18n audit report (generated by cms:admin-i18n-audit), identifies
 * translation keys that are missing from import payloads, and attempts to restore them from
 * a historical SQL translate inventory. Recovered rows are written to sidecar PHP payload files
 * (one per module) that are merged at import time. Optionally synchronises recovered rows
 * directly to the database within a single transaction.
 *
 * Usage: php artisan cms:admin-i18n-recover
 * Options:
 *   --frontend          Path to the base-admin workspace root
 *   --export            Path to the core exported translates.php payload
 *   --modules-root      Path to the Laravel cms modules root
 *   --runtime-dir       Path to generated admin runtime packs
 *   --report            Path to the latest admin audit JSON report
 *   --history           Path to the historical SQL translate inventory
 *   --core-recovery     Path to the root admin recovery sidecar payload
 *   --module-sidecar    File name for module recovery sidecars (default: translate-admin-recovered.php)
 *   --write-report      Write a recovery JSON and Markdown report (0/1)
 *   --sync-db           Create or reconcile DB rows needed by recovered admin keys (0/1)
 *   --refresh-report    Re-run cms:admin-i18n-audit before recovering (0/1)
 *   --refresh-usage     Pass refresh-usage through to cms:admin-i18n-audit when refreshing (0/1)
 *
 * @package Cms\Core\Console\Commands
 * @author  iSPA Team
 * @since   8.0.0 (2026-03-17)
 */
class AdminI18nRecoverCommand extends Command
{
    protected $signature = 'cms:admin-i18n-recover
        {--frontend= : Path to the base-admin workspace root}
        {--export= : Path to the core exported translates.php payload}
        {--modules-root= : Path to the Laravel cms modules root}
        {--runtime-dir= : Path to generated admin runtime packs}
        {--report= : Path to the latest admin audit JSON report}
        {--history= : Path to the historical SQL translate inventory}
        {--core-recovery= : Path to the root admin recovery sidecar payload}
        {--module-sidecar=translate-admin-recovered.php : File name for module recovery sidecars}
        {--write-report=1 : Write a recovery JSON and Markdown report (0/1)}
        {--sync-db=0 : Create or reconcile DB rows needed by recovered admin keys (0/1)}
        {--refresh-report=0 : Re-run cms:admin-i18n-audit before recovering (0/1)}
        {--refresh-usage=0 : Pass refresh usage through to cms:admin-i18n-audit when refreshing the report (0/1)}';

    protected $description = 'Recover missing admin translation payload rows from approved historical inventories';

    /**
     * Execute the console command.
     *
     * Loads the audit report, resolves recoverable keys against the historical inventory,
     * writes sidecar payload files, optionally syncs recovered rows to the database,
     * and writes a structured recovery report.
     *
     * @return int Command::SUCCESS or Command::FAILURE
     */
    public function handle(): int
    {
        $frontendRoot = $this->normalizePath(
            $this->option('frontend') ?: base_path('../base-admin')
        );
        $exportPath = $this->normalizePath(
            $this->option('export') ?: base_path('cms/Core/database/seeders/exported/translates.php')
        );
        $modulesRoot = $this->normalizePath(
            $this->option('modules-root') ?: base_path('cms')
        );
        $runtimeDir = $this->normalizePath(
            $this->option('runtime-dir')
            ?: storage_path('app/public/i18n/' . config('ispa-cms.app_version') . '/adm')
        );
        $reportPath = $this->normalizePath(
            $this->option('report') ?: storage_path('app/reports/admin-i18n/admin-i18n-audit-latest.json')
        );
        $historyPath = $this->normalizePath(
            $this->option('history') ?: base_path('database/seeders/sql/translates.php')
        );
        $coreRecoveryPath = $this->normalizePath(
            $this->option('core-recovery') ?: dirname($exportPath) . '/translates-admin-recovered.php'
        );
        $moduleSidecarName = trim((string) $this->option('module-sidecar')) ?: 'translate-admin-recovered.php';

        if (! File::exists($exportPath)) {
            $this->error("Core export payload not found: {$exportPath}");
            return self::FAILURE;
        }

        if (! File::exists($historyPath)) {
            $this->error("Historical SQL translate inventory not found: {$historyPath}");
            return self::FAILURE;
        }

        $this->ensureAuditReport(
            $frontendRoot,
            $exportPath,
            $modulesRoot,
            $runtimeDir,
            $reportPath
        );

        $report = $this->loadJsonFile($reportPath);
        if ($report === null) {
            $this->error("Admin audit report is not valid JSON: {$reportPath}");
            return self::FAILURE;
        }

        $historyRows = $this->loadHistoricalRows($historyPath, $modulesRoot);
        $historyIndex = $this->buildRecoveryIndex($historyRows);

        $recoveries = $this->resolveMissingImportRecoveries($report, $historyIndex);
        $writtenFiles = $this->writeRecoverySidecars(
            $recoveries['recovered'],
            $coreRecoveryPath,
            $modulesRoot,
            $moduleSidecarName
        );

        $dbSync = [
            'created' => 0,
            'updated' => 0,
            'skipped' => 0,
            'ambiguous' => 0,
            'processed' => 0,
        ];

        if ($this->asBoolean($this->option('sync-db'))) {
            $desiredRows = $this->collectDbDesiredRows(
                $exportPath,
                $coreRecoveryPath,
                $modulesRoot,
                $moduleSidecarName,
                $report,
                $recoveries['recovered']
            );

            $dbSync = $this->syncDesiredRowsToDatabase($desiredRows);
        }

        $recoveryReport = $this->buildRecoveryReport(
            $reportPath,
            $historyPath,
            $coreRecoveryPath,
            $moduleSidecarName,
            $recoveries,
            $writtenFiles,
            $dbSync
        );

        $this->renderSummary($recoveryReport);

        if ($this->asBoolean($this->option('write-report'))) {
            $paths = $this->writeRecoveryReportFiles(dirname($reportPath), $recoveryReport);
            $this->line("Recovery JSON: {$paths['json']}");
            $this->line("Recovery Markdown: {$paths['markdown']}");
        }

        return self::SUCCESS;
    }

    private function normalizePath(string $path): string
    {
        $path = trim($path);

        if ($path === '') {
            return $path;
        }

        $real = realpath($path);
        if ($real !== false) {
            return str_replace('\\', '/', $real);
        }

        return str_replace('\\', '/', $path);
    }

    private function asBoolean(mixed $value): bool
    {
        return (string) $value === '1' || $value === true || $value === 1;
    }

    /**
     * Ensure the audit report exists, refreshing it if required.
     *
     * @throws \RuntimeException When cms:admin-i18n-audit fails before recovery.
     */
    private function ensureAuditReport(
        string $frontendRoot,
        string $exportPath,
        string $modulesRoot,
        string $runtimeDir,
        string $reportPath
    ): void {
        if (! $this->asBoolean($this->option('refresh-report')) && File::exists($reportPath)) {
            return;
        }

        $this->info('Refreshing the admin i18n audit report before recovery...');

        $exit = Artisan::call('cms:admin-i18n-audit', [
            '--frontend' => $frontendRoot,
            '--export' => $exportPath,
            '--modules-root' => $modulesRoot,
            '--runtime-dir' => $runtimeDir,
            '--report-dir' => dirname($reportPath),
            '--write-report' => 1,
            '--strict' => 0,
            '--refresh-usage' => $this->asBoolean($this->option('refresh-usage')) ? 1 : 0,
        ]);

        if ($exit !== 0) {
            throw new \RuntimeException('cms:admin-i18n-audit failed before recovery: ' . trim(Artisan::output()));
        }
    }

    private function loadJsonFile(string $path): ?array
    {
        if (! File::exists($path)) {
            return null;
        }

        try {
            $decoded = json_decode((string) File::get($path), true, 512, JSON_THROW_ON_ERROR);
        } catch (Throwable) {
            return null;
        }

        return is_array($decoded) ? $decoded : null;
    }

    private function loadHistoricalRows(string $historyPath, string $modulesRoot): array
    {
        $rows = [];

        $this->appendNormalizedRows(
            $rows,
            $this->requirePayloadFile($historyPath),
            'root-history',
            null
        );

        foreach ($this->discoverModulePayloadPaths($modulesRoot, 'translate.php') as $module => $path) {
            $this->appendNormalizedRows(
                $rows,
                $this->requirePayloadFile($path),
                'module-history',
                $module
            );
        }

        return $rows;
    }

    private function requirePayloadFile(string $path): array
    {
        if (! File::exists($path)) {
            return [];
        }

        $payload = require $path;

        return is_array($payload) ? $payload : [];
    }

    private function discoverModulePayloadPaths(string $modulesRoot, string $basename): array
    {
        $paths = [];

        if (! File::isDirectory($modulesRoot)) {
            return $paths;
        }

        foreach (File::directories($modulesRoot) as $modulePath) {
            $module = basename($modulePath);
            $candidate = $modulePath . '/database/seeders/sql/' . $basename;

            if (File::exists($candidate)) {
                $paths[$module] = $candidate;
            }
        }

        ksort($paths);

        return $paths;
    }

    private function appendNormalizedRows(array &$buffer, array $rows, string $source, ?string $moduleHint): void
    {
        foreach ($rows as $row) {
            $normalized = $this->normalizeSourceRow($row, $source, $moduleHint);
            if ($normalized === null) {
                continue;
            }

            $key = $normalized['canonical_key'] . '|' . $source . '|' . ($moduleHint ?? 'root');
            if (! isset($buffer[$key]) || $this->isPreferredRow($normalized, $buffer[$key])) {
                $buffer[$key] = $normalized;
            }
        }
    }

    private function normalizeSourceRow(mixed $row, string $source, ?string $moduleHint): ?array
    {
        if (! is_array($row)) {
            return null;
        }

        $groupName = trim((string) ($row['group_name'] ?? ''));
        $rawName = trim((string) ($row['name'] ?? ''));

        if ($groupName === '' || $rawName === '') {
            return null;
        }

        $canonicalKey = $this->resolveCanonicalImportKey($groupName, $rawName);
        $fullName = Str::startsWith($rawName, $groupName . '.')
            ? $rawName
            : $groupName . '.' . $rawName;

        $modules = $this->normalizeModulesPayload($row['modules'] ?? []);
        if ($moduleHint !== null && ! in_array($moduleHint, $modules, true)) {
            $modules[] = $moduleHint;
        }

        sort($modules);

        return [
            'id' => $this->normalizeId($row['id'] ?? null),
            'group_name' => $groupName,
            'name' => $rawName,
            'full_name' => $fullName,
            'canonical_key' => $canonicalKey,
            'text' => $this->normalizeTextPayload($row['text'] ?? []),
            'modules' => $modules,
            'for_web' => (bool) ($row['for_web'] ?? false),
            'for_adm' => (bool) ($row['for_adm'] ?? false),
            'for_app' => (bool) ($row['for_app'] ?? false),
            'status' => $this->normalizeOptionalString($row['status'] ?? null),
            'created_at' => $this->normalizeOptionalString($row['created_at'] ?? null),
            'updated_at' => $this->normalizeOptionalString($row['updated_at'] ?? null),
            'source' => $source,
            'module_hint' => $moduleHint,
        ];
    }

    private function normalizeId(mixed $value): ?int
    {
        $id = filter_var($value, FILTER_VALIDATE_INT, ['options' => ['min_range' => 1]]);

        return $id === false ? null : $id;
    }

    private function normalizeModulesPayload(mixed $modules): array
    {
        if (is_string($modules)) {
            $decoded = json_decode($modules, true);
            $modules = is_array($decoded) ? $decoded : [$modules];
        }

        if (! is_array($modules)) {
            return [];
        }

        $normalized = [];
        foreach ($modules as $module) {
            if (! is_scalar($module)) {
                continue;
            }

            $value = trim((string) $module);
            if ($value === '') {
                continue;
            }

            $normalized[$value] = true;
        }

        return array_values(array_keys($normalized));
    }

    private function normalizeTextPayload(mixed $text): array
    {
        if (is_string($text)) {
            $decoded = json_decode($text, true);
            $text = is_array($decoded) ? $decoded : [];
        }

        if (! is_array($text)) {
            return [];
        }

        ksort($text);

        return $text;
    }

    private function normalizeOptionalString(mixed $value): ?string
    {
        if ($value === null) {
            return null;
        }

        $value = trim((string) $value);

        return $value === '' ? null : $value;
    }

    private function resolveCanonicalImportKey(string $groupName, string $name): string
    {
        $base = Str::startsWith($name, $groupName . '.')
            ? Str::after($name, $groupName . '.')
            : $name;

        if ($groupName === 'validation') {
            if (Str::startsWith($base, 'v.a.')) {
                $base = 'attributes.' . Str::after($base, 'v.a.');
            } elseif (Str::startsWith($base, 'a.')) {
                $base = 'attributes.' . Str::after($base, 'a.');
            }
        }

        return $groupName . '.' . $base;
    }

    private function isPreferredRow(array $candidate, array $current): bool
    {
        $candidateScore = ($candidate['for_adm'] ? 4 : 0)
            + ($candidate['source'] === 'root-history' ? 2 : 0)
            + ($candidate['module_hint'] !== null ? 1 : 0);
        $currentScore = ($current['for_adm'] ? 4 : 0)
            + ($current['source'] === 'root-history' ? 2 : 0)
            + ($current['module_hint'] !== null ? 1 : 0);

        return $candidateScore > $currentScore;
    }

    private function buildRecoveryIndex(array $rows): array
    {
        $bestRows = [];
        foreach ($rows as $row) {
            $canonicalKey = $row['canonical_key'];

            if (! isset($bestRows[$canonicalKey]) || $this->isPreferredRow($row, $bestRows[$canonicalKey])) {
                $bestRows[$canonicalKey] = $row;
            }
        }

        $aliases = [];
        foreach ($bestRows as $canonicalKey => $row) {
            $rowAliases = array_merge(
                $this->buildAliasesForCanonicalKey($canonicalKey),
                [$row['name'], $row['full_name']]
            );

            foreach (array_values(array_unique(array_filter($rowAliases))) as $alias) {
                $aliases[$alias][$canonicalKey] = true;
            }
        }

        foreach ($aliases as $alias => $matches) {
            $aliases[$alias] = array_values(array_keys($matches));
        }

        return [
            'aliases' => $aliases,
            'rows' => $bestRows,
        ];
    }

    private function buildAliasesForCanonicalKey(string $canonicalKey): array
    {
        $group = Str::before($canonicalKey, '.');
        $base = Str::after($canonicalKey, $group . '.');
        $aliases = [$canonicalKey];

        if ($group === 'validation') {
            if (Str::startsWith($base, 'attributes.')) {
                $aliases[] = 'v.a.' . Str::after($base, 'attributes.');
            }

            return array_values(array_unique($aliases));
        }

        $shortGroup = mb_substr($group, 0, 1);
        $aliases[] = $shortGroup . '.' . $base;

        $adminAlias = $this->buildAdminAlias($shortGroup, $base);
        if ($adminAlias !== null) {
            $aliases[] = $adminAlias;
        }

        return array_values(array_unique($aliases));
    }

    private function buildAdminAlias(string $shortGroup, string $baseName): ?string
    {
        $baseName = trim($baseName);
        if ($baseName === '') {
            return null;
        }

        if (! Str::contains($baseName, '.')) {
            return $shortGroup . '.' . $baseName;
        }

        $segments = explode('.', $baseName);
        $first = array_shift($segments);

        $firstAlias = match ($first) {
            'attributes' => 'a',
            'between' => 'bw',
            default => $first,
        };

        return $shortGroup . '.' . implode('.', array_filter([$firstAlias, ...$segments]));
    }

    private function resolveMissingImportRecoveries(array $report, array $historyIndex): array
    {
        $recovered = [];
        $unresolved = [];

        $candidates = array_merge(
            $report['core_missing_candidates'] ?? [],
            $report['module_missing_candidates'] ?? []
        );

        foreach ($candidates as $candidate) {
            $key = trim((string) ($candidate['key'] ?? ''));
            if ($key === '') {
                continue;
            }

            $canonicalMatches = $historyIndex['aliases'][$key] ?? [];
            if (count($canonicalMatches) !== 1) {
                $unresolved[] = [
                    'key' => $key,
                    'reason' => count($canonicalMatches) === 0 ? 'no_history_match' : 'ambiguous_history_match',
                    'ownership' => $candidate['ownership'] ?? [],
                ];
                continue;
            }

            $canonicalKey = $canonicalMatches[0];
            $sourceRow = $historyIndex['rows'][$canonicalKey] ?? null;
            if ($sourceRow === null) {
                $unresolved[] = [
                    'key' => $key,
                    'reason' => 'missing_source_row',
                    'ownership' => $candidate['ownership'] ?? [],
                ];
                continue;
            }

            $recovered[] = [
                'key' => $key,
                'canonical_key' => $canonicalKey,
                'ownership' => $candidate['ownership'] ?? [],
                'source_row' => $sourceRow,
            ];
        }

        return [
            'recovered' => $recovered,
            'unresolved' => $unresolved,
        ];
    }

    private function writeRecoverySidecars(
        array $recoveries,
        string $coreRecoveryPath,
        string $modulesRoot,
        string $moduleSidecarName
    ): array {
        $sidecars = [];

        $existingCoreRows = $this->loadSidecarRows($coreRecoveryPath, 'root-sidecar', null);
        if (! empty($existingCoreRows)) {
            $sidecars[$coreRecoveryPath] = $existingCoreRows;
        }

        foreach ($this->discoverModulePayloadPaths($modulesRoot, $moduleSidecarName) as $module => $path) {
            $existingModuleRows = $this->loadSidecarRows($path, 'module-sidecar', $module);
            if (! empty($existingModuleRows)) {
                $sidecars[$path] = $existingModuleRows;
            }
        }

        foreach ($recoveries as $recovery) {
            $target = $this->determineTargetSidecar(
                $recovery['ownership'] ?? [],
                $coreRecoveryPath,
                $modulesRoot,
                $moduleSidecarName
            );

            $row = $this->buildTargetPayloadRow(
                $recovery['source_row'],
                $recovery['ownership'] ?? [],
                $target['type'],
                $target['module']
            );

            $rowKey = $row['group_name'] . '|' . $row['name'];
            $sidecars[$target['path']][$rowKey] = $row;
        }

        $written = [];

        foreach ($sidecars as $path => $rowsByKey) {
            $rows = array_values($rowsByKey);
            usort($rows, static fn ($a, $b) => [$a['group_name'], $a['name']] <=> [$b['group_name'], $b['name']]);
            $this->writePayloadSidecar($path, $rows);

            $written[] = [
                'path' => $path,
                'rows' => count($rows),
            ];
        }

        return $written;
    }

    private function loadSidecarRows(string $path, string $source, ?string $moduleHint): array
    {
        $rows = [];

        foreach ($this->requirePayloadFile($path) as $row) {
            $normalized = $this->normalizeSourceRow($row, $source, $moduleHint);
            if ($normalized === null) {
                continue;
            }

            $payload = $this->buildTargetPayloadRow(
                $normalized,
                ['core' => $moduleHint === null, 'modules' => $moduleHint ? [$moduleHint] : []],
                $moduleHint === null ? 'core' : 'module',
                $moduleHint
            );

            $rows[$payload['group_name'] . '|' . $payload['name']] = $payload;
        }

        return $rows;
    }

    private function determineTargetSidecar(
        array $ownership,
        string $coreRecoveryPath,
        string $modulesRoot,
        string $moduleSidecarName
    ): array {
        $modules = array_values(array_filter($ownership['modules'] ?? [], static fn ($module) => is_string($module) && $module !== ''));
        $coreOwned = (bool) ($ownership['core'] ?? false);

        if ($coreOwned || count($modules) !== 1) {
            return [
                'type' => 'core',
                'module' => null,
                'path' => $coreRecoveryPath,
            ];
        }

        $module = $modules[0];

        return [
            'type' => 'module',
            'module' => $module,
            'path' => $modulesRoot . '/' . $module . '/database/seeders/sql/' . $moduleSidecarName,
        ];
    }

    private function buildTargetPayloadRow(
        array $sourceRow,
        array $ownership,
        string $targetType,
        ?string $targetModule
    ): array {
        $modules = $sourceRow['modules'] ?? [];
        foreach (($ownership['modules'] ?? []) as $module) {
            if (is_string($module) && $module !== '') {
                $modules[] = $module;
            }
        }

        if ($targetModule !== null) {
            $modules[] = $targetModule;
        }

        $modules = array_values(array_unique(array_filter($modules)));
        sort($modules);

        $name = $targetType === 'core'
            ? $sourceRow['full_name']
            : $this->normalizeModulePayloadName($sourceRow['group_name'], $sourceRow['full_name']);

        $payload = [
            'modules' => $modules,
            'group_name' => $sourceRow['group_name'],
            'name' => $name,
            'text' => $sourceRow['text'],
            'for_web' => (int) ($sourceRow['for_web'] ?? false),
            'for_adm' => 1,
            'for_app' => (int) ($sourceRow['for_app'] ?? false),
            'status' => $sourceRow['status'],
            'created_at' => $sourceRow['created_at'],
            'updated_at' => $sourceRow['updated_at'],
        ];

        // no id. Ids of module translation files link rows across modules (TranslationSidecarIdsTest).
        return $payload;
    }

    private function normalizeModulePayloadName(string $groupName, string $fullName): string
    {
        $name = (string) str($fullName)->replaceFirst($groupName . '.', '');

        if ($groupName !== 'validation') {
            return $name;
        }

        return match (true) {
            str_starts_with($name, 'a.') => 'attributes.' . substr($name, 2),
            str_starts_with($name, 'v.a.') => 'attributes.' . substr($name, 4),
            default => $name,
        };
    }

    private function writePayloadSidecar(string $path, array $rows): void
    {
        File::ensureDirectoryExists(dirname($path));

        $header = <<<PHP
<?php
/**
 * Admin i18n recovery sidecar.
 * This file is curated for admin-safe translation recovery and is merged at import time.
 */

return 
PHP;

        \Cms\Core\Support\Testing\TranslationFileGuard::assertWritable($path);
        File::put($path, $header . var_export($rows, true) . ";\n");
    }

    private function collectDbDesiredRows(
        string $exportPath,
        string $coreRecoveryPath,
        string $modulesRoot,
        string $moduleSidecarName,
        array $report,
        array $recoveries
    ): array {
        $currentRows = [];

        $this->appendNormalizedRows($currentRows, $this->requirePayloadFile($exportPath), 'core-export', null);
        $this->appendNormalizedRows($currentRows, $this->requirePayloadFile($coreRecoveryPath), 'core-sidecar', null);

        foreach ($this->discoverModulePayloadPaths($modulesRoot, 'translate.php') as $module => $path) {
            $this->appendNormalizedRows($currentRows, $this->requirePayloadFile($path), 'module-export', $module);
        }

        foreach ($this->discoverModulePayloadPaths($modulesRoot, $moduleSidecarName) as $module => $path) {
            $this->appendNormalizedRows($currentRows, $this->requirePayloadFile($path), 'module-sidecar', $module);
        }

        $currentIndex = $this->buildRecoveryIndex($currentRows);
        $desired = [];

        foreach ($recoveries as $recovery) {
            $canonicalKey = $recovery['canonical_key'] ?? null;
            if (is_string($canonicalKey) && isset($currentIndex['rows'][$canonicalKey])) {
                $desired[$canonicalKey] = $currentIndex['rows'][$canonicalKey];
            }
        }

        foreach ($report['runtime_missing_candidates'] ?? [] as $candidate) {
            $canonicalCandidates = array_values(array_filter($candidate['canonical_candidates'] ?? [], 'is_string'));

            if (count($canonicalCandidates) === 1 && isset($currentIndex['rows'][$canonicalCandidates[0]])) {
                $desired[$canonicalCandidates[0]] = $currentIndex['rows'][$canonicalCandidates[0]];
                continue;
            }

            $key = trim((string) ($candidate['key'] ?? ''));
            if ($key === '') {
                continue;
            }

            $aliasMatches = $currentIndex['aliases'][$key] ?? [];
            if (count($aliasMatches) === 1 && isset($currentIndex['rows'][$aliasMatches[0]])) {
                $desired[$aliasMatches[0]] = $currentIndex['rows'][$aliasMatches[0]];
            }
        }

        return array_values($desired);
    }

    private function syncDesiredRowsToDatabase(array $rows): array
    {
        $summary = [
            'created' => 0,
            'updated' => 0,
            'skipped' => 0,
            'ambiguous' => 0,
            'processed' => count($rows),
        ];

        DB::transaction(function () use ($rows, &$summary): void {
            foreach ($rows as $row) {
                $existing = $this->resolveExistingTranslation($row);

                if (is_array($existing) && ($existing['ambiguous'] ?? false)) {
                    ++$summary['ambiguous'];
                    continue;
                }

                if ($existing instanceof Translate) {
                    if ($this->reconcileExistingTranslation($existing, $row)) {
                        ++$summary['updated'];
                    } else {
                        ++$summary['skipped'];
                    }

                    continue;
                }

                Translate::query()->create([
                    'modules' => $row['modules'],
                    'group_name' => $row['group_name'],
                    'name' => $row['name'],
                    'text' => $row['text'],
                    'for_web' => (bool) ($row['for_web'] ?? false),
                    'for_adm' => (bool) ($row['for_adm'] ?? false),
                    'for_app' => (bool) ($row['for_app'] ?? false),
                    'status' => $row['status'],
                ]);
                ++$summary['created'];
            }
        });

        return $summary;
    }

    private function resolveExistingTranslation(array $row): Translate|array|null
    {
        $name = trim((string) ($row['name'] ?? ''));
        $groupName = trim((string) ($row['group_name'] ?? ''));

        $fullName = Str::startsWith($name, $groupName . '.')
            ? $name
            : $groupName . '.' . $name;
        $moduleStyleName = $this->normalizeModulePayloadName($groupName, $fullName);

        $nameCandidates = array_values(array_unique(array_filter([
            mb_strtolower($name),
            mb_strtolower($fullName),
            mb_strtolower($moduleStyleName),
        ])));

        $matches = Translate::query()
            ->where('group_name', $groupName)
            ->where(function ($query) use ($nameCandidates): void {
                foreach ($nameCandidates as $candidate) {
                    $query->orWhereRaw('LOWER(name) = ?', [$candidate]);
                }
            })
            ->get();

        if ($matches->isEmpty()) {
            return null;
        }

        if ($matches->count() === 1) {
            return $matches->first();
        }

        $canonicalMatches = $matches->filter(function (Translate $translate) use ($row) {
            return $this->resolveCanonicalImportKey(
                trim((string) $translate->group_name),
                trim((string) $translate->name)
            ) === $row['canonical_key'];
        })->values();

        if ($canonicalMatches->count() === 1) {
            return $canonicalMatches->first();
        }

        $exactName = $matches->first(function (Translate $translate) use ($name) {
            return mb_strtolower((string) $translate->name) === mb_strtolower($name);
        });

        if ($exactName !== null) {
            return $exactName;
        }

        return ['ambiguous' => true];
    }

    private function reconcileExistingTranslation(Translate $translate, array $row): bool
    {
        $dirty = false;
        $currentModules = $this->normalizeModulesPayload($translate->modules ?? []);
        $mergedModules = array_values(array_unique(array_merge($currentModules, $row['modules'] ?? [])));
        sort($mergedModules);

        if ($mergedModules !== $currentModules) {
            $translate->modules = $mergedModules;
            $dirty = true;
        }

        if (! $translate->for_adm && ($row['for_adm'] ?? false)) {
            $translate->for_adm = true;
            $dirty = true;
        }

        if (! $translate->for_web && ($row['for_web'] ?? false)) {
            $translate->for_web = true;
            $dirty = true;
        }

        if (! $translate->for_app && ($row['for_app'] ?? false)) {
            $translate->for_app = true;
            $dirty = true;
        }

        if ($this->normalizeTextPayload($translate->text ?? []) === [] && $this->normalizeTextPayload($row['text'] ?? []) !== []) {
            $translate->text = $row['text'];
            $dirty = true;
        }

        if ($translate->status === null && ($row['status'] ?? null) !== null) {
            $translate->status = $row['status'];
            $dirty = true;
        }

        if ($dirty) {
            $translate->save();
        }

        return $dirty;
    }

    private function buildRecoveryReport(
        string $reportPath,
        string $historyPath,
        string $coreRecoveryPath,
        string $moduleSidecarName,
        array $recoveries,
        array $writtenFiles,
        array $dbSync
    ): array {
        return [
            'generated_at' => now()->toAtomString(),
            'inputs' => [
                'audit_report' => $reportPath,
                'history_path' => $historyPath,
                'core_recovery_path' => $coreRecoveryPath,
                'module_sidecar_name' => $moduleSidecarName,
            ],
            'summary' => [
                'recovered_count' => count($recoveries['recovered']),
                'unresolved_count' => count($recoveries['unresolved']),
                'sidecars_written' => count($writtenFiles),
                'db_processed' => $dbSync['processed'],
                'db_created' => $dbSync['created'],
                'db_updated' => $dbSync['updated'],
                'db_skipped' => $dbSync['skipped'],
                'db_ambiguous' => $dbSync['ambiguous'],
            ],
            'recovered' => array_map(function (array $row) {
                return [
                    'key' => $row['key'],
                    'canonical_key' => $row['canonical_key'],
                    'source' => $row['source_row']['source'],
                    'source_name' => $row['source_row']['full_name'],
                    'ownership' => $row['ownership'],
                ];
            }, $recoveries['recovered']),
            'unresolved' => $recoveries['unresolved'],
            'written_files' => $writtenFiles,
        ];
    }

    private function renderSummary(array $report): void
    {
        $summary = $report['summary'];

        $this->info('Admin i18n recovery completed.');
        $this->line('Recovered rows: ' . $summary['recovered_count']);
        $this->line('Unresolved rows: ' . $summary['unresolved_count']);
        $this->line('Sidecar files written: ' . $summary['sidecars_written']);
        $this->line('DB rows created: ' . $summary['db_created']);
        $this->line('DB rows updated: ' . $summary['db_updated']);
        $this->line('DB rows skipped: ' . $summary['db_skipped']);
    }

    private function writeRecoveryReportFiles(string $reportDir, array $report): array
    {
        File::ensureDirectoryExists($reportDir);

        $jsonPath = $reportDir . '/admin-i18n-recovery-latest.json';
        $markdownPath = $reportDir . '/admin-i18n-recovery-latest.md';

        File::put(
            $jsonPath,
            json_encode($report, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR)
        );
        File::put($markdownPath, $this->buildMarkdownReport($report));

        return [
            'json' => $jsonPath,
            'markdown' => $markdownPath,
        ];
    }

    private function buildMarkdownReport(array $report): string
    {
        $lines = [
            '# Admin i18n Recovery',
            '',
            'Generated at: ' . ($report['generated_at'] ?? ''),
            '',
            '## Summary',
            '',
            '- Recovered rows: ' . ($report['summary']['recovered_count'] ?? 0),
            '- Unresolved rows: ' . ($report['summary']['unresolved_count'] ?? 0),
            '- Sidecar files written: ' . ($report['summary']['sidecars_written'] ?? 0),
            '- DB rows created: ' . ($report['summary']['db_created'] ?? 0),
            '- DB rows updated: ' . ($report['summary']['db_updated'] ?? 0),
            '',
            '## Recovered',
            '',
        ];

        foreach ($report['recovered'] ?? [] as $item) {
            $lines[] = '- `' . $item['key'] . '` -> `' . $item['canonical_key'] . '`';
            $lines[] = '  source: ' . $item['source_name'];
        }

        if (empty($report['recovered'])) {
            $lines[] = '- none';
        }

        $lines[] = '';
        $lines[] = '## Unresolved';
        $lines[] = '';

        foreach ($report['unresolved'] ?? [] as $item) {
            $lines[] = '- `' . $item['key'] . '` (' . ($item['reason'] ?? 'unknown') . ')';
        }

        if (empty($report['unresolved'])) {
            $lines[] = '- none';
        }

        return implode("\n", $lines) . "\n";
    }
