declare(strict_types=1);

namespace Cms\Core\Services\Admin;

use Illuminate\Support\Facades\File;

/**
 * Builds public/iPanel/config.js: the run-time site values the Vue admin reads from `window.__ISPA_ADMIN__` before
 * falling back to its baked `VITE_*` values.
 *
 * Values come from the already loaded configuration (.env): APP_URL, SESSION_DOMAIN, SESSION_SECURE_COOKIE,
 * ISPA_ADMIN_AUTH_KEY, PLATFORM_HUB_URL and VERSION. The file is generated, never edited by hand.
 */
class AdminRuntimeConfig
{
    /** Hub URL used when PLATFORM_HUB_URL is set to an empty value. */
    private const DEFAULT_HUB_URL = 'https://ispa.tech';

    /**
     * The values the admin needs.
     *
     * - url: APP_URL with exactly one trailing slash (scheme, port and path are kept).
     * - cookieDomain: SESSION_DOMAIN exactly as Laravel stores it (a leading dot is kept, the browser accepts it);
     *   when it is empty, the bare host of APP_URL (no port).
     * - secureCookie: SESSION_SECURE_COOKIE when it is set, else whether APP_URL uses https.
     *
     * @return array{url: string, cookieDomain: string, secureCookie: bool, adminAuthKey: string, hubUrl: string, version: string}
     */
    public function values(): array
    {
        $appUrl = trim((string) config('app.url', ''));
        $parts = parse_url($appUrl) ?: [];
        $host = (string) ($parts['host'] ?? '');

        $sessionDomain = trim((string) config('session.domain', ''));
        $rawSecure = config('session.secure');
        // filter_var() turns null and '' into false, so an unset value is checked first.
        $secure = $rawSecure === null || $rawSecure === ''
            ? null
            : filter_var($rawSecure, FILTER_VALIDATE_BOOLEAN, FILTER_NULL_ON_FAILURE);

        $hubUrl = trim((string) config('ispa-cms.platform_hub_url', ''));

        return [
            'url' => $appUrl === '' ? 'http://localhost/' : rtrim($appUrl, '/').'/',
            'cookieDomain' => $sessionDomain !== '' ? $sessionDomain : $host,
            'secureCookie' => $secure ?? (strtolower((string) ($parts['scheme'] ?? '')) === 'https'),
            'adminAuthKey' => (string) config('ispa-cms.admin_auth_key', ''),
            'hubUrl' => $hubUrl !== '' ? $hubUrl : self::DEFAULT_HUB_URL,
            'version' => (string) config('ispa-cms.app_version', ''),
            'docsUrl' => rtrim((string) config('ispa-cms.docs_url', 'https://docs.ispa.tech'), '/'),
        ];
    }

    /**
     * The file body. The header comment is a constant (no site value can reach it); the JSON escapes `<`, `>` and
     * `&` so a value cannot close the script tag or break out of the literal.
     */
    public function render(): string
    {
        $json = json_encode($this->values(), JSON_HEX_TAG | JSON_HEX_AMP | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);

        return "// Generated by `php artisan cms:admin-config` from .env; do not edit. The admin key is not a secret: every admin request sends it.\n"
            ."window.__ISPA_ADMIN__ = {$json};\n";
    }

    /**
     * Write the file and return its path.
     *
     * @param string|null $path Target file (default: public/iPanel/config.js)
     */
    public function write(?string $path = null): string
    {
        $path ??= public_path('iPanel/config.js');
        File::ensureDirectoryExists(dirname($path));
        $body = $this->render();
        File::put($path, $body);
        $this->versionIndexScript(dirname($path).'/index.html', $body);

        return $path;
    }

    /**
     * Point the config script tag of the sibling index.html at `config.js?v=<hash of the body>`.
     *
     * Per-site nginx confs cache every `.js` for good while index.html is served no-cache, so the changing query
     * string is what makes a browser fetch a new config.js. Idempotent: an existing `?v=` is replaced, the file is
     * not touched when the tag is already right, and a missing index.html or tag is ignored. The new file is written
     * next to the old one and renamed over it, so a reader never sees a half-written page; permissions are kept.
     */
    private function versionIndexScript(string $index, string $configBody): void
    {
        if (! is_file($index)) {
            return;
        }

        $html = (string) file_get_contents($index);
        $src = '/iPanel/config.js?v='.substr(sha1($configBody), 0, 12);
        $updated = preg_replace_callback(
            '~(<script\b[^>]*?\bsrc=)(["\'])/iPanel/config\.js(?:\?v=[^"\']*)?\2~i',
            static fn (array $m): string => $m[1].$m[2].$src.$m[2],
            $html,
        );

        if ($updated === null || $updated === $html) {
            return;
        }

        $tmp = $index.'.tmp'.getmypid();
        if (file_put_contents($tmp, $updated) === false) {
            return;
        }
        @chmod($tmp, fileperms($index) & 0777);
        if (! @rename($tmp, $index)) {
            @unlink($tmp);
        }
    }
}
