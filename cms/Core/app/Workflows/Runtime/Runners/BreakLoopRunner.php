namespace Cms\Core\Workflows\Runtime\Runners;

use Cms\Core\Workflows\Runtime\Contracts\StepRunner;
use Cms\Core\Workflows\Runtime\StepDefinition;
use Cms\Core\Workflows\Runtime\StepRunResult;
use Cms\Core\Workflows\Runtime\WorkflowContext;

/**
 * Executes a break-loop step that signals the workflow executor to exit the current loop.
 *
 * Returns a success result with a "break" edge hint, causing the graph executor to
 * follow the break-designated connection out of the loop.
 *
 * @see StepRunner
 * @package Cms\Core\Workflows\Runtime\Runners
 * @author  iSPA Team
 * @since   8.0.0 (2026-03-17)
 */
class BreakLoopRunner implements StepRunner
{
    /**
     * {@inheritdoc}
     * @param  StepDefinition $step
     * @param  WorkflowContext $context
     * @return StepRunResult
     */
    public function run(StepDefinition $step, WorkflowContext $context): StepRunResult
    {
        $logs = [
            ['action' => 'break_loop', 'level' => 'info', 'message' => 'Break loop requested'],
        ];

        return StepRunResult::success(['action' => 'break'], $logs, 'break');
    }
}
