namespace Cms\Content\Jobs;

use Illuminate\Bus\Queueable;
use Cms\Content\Models\Content;
use Illuminate\Queue\SerializesModels;
use Illuminate\Queue\InteractsWithQueue;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Foundation\Bus\Dispatchable;

class TextTranslationJob implements ShouldQueue
{
    /** @var bool */
    public bool $isDiscovery = false;


    use Dispatchable, InteractsWithQueue, Queueable, SerializesModels;

    /**
     * Create a new job instance.
     */
    public function __construct()
    {
        //
    }

    /**
     * Execute the job.
     */
    public function handle(): void
    {
        //  Get vietnamese content by published status order by last updated
        $content = Content::where([
            'language_id' => 1,
            'is_confirmed' => true,
        ])->orderBy('updated_at', 'desc')->with('contents')->first();

        if (!$content) {
            return;
        }


    }
}
